function getInitials(name: string): string {
  const words = (name || "")
    .replace(/[^A-Za-z0-9 ]/g, " ")
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  if (words.length > 1) {
    return (words[0][0] + words[1][0]).toUpperCase();
  }
  return (words[0] || name || "").slice(0, 2).toUpperCase();
}

function PartnerTile({ partner }: { partner: PartnerItem }) {
  const [imgError, setImgError] = useState(false);
  const rawLogo = (partner.logo || "").trim();
  const imgSrc = rawLogo
    ? /^https?:\/\//i.test(rawLogo)
      ? rawLogo
      : rawLogo.startsWith("/")
      ? rawLogo
      : `/${rawLogo}`
    : "";

  const tileContent = (
    <>
      <div className="logo">
        {imgSrc && !imgError ? (
          /* eslint-disable-next-line @next/next/no-img-element */
          <img
            src={imgSrc}
            alt={partner.name}
            onError={() => setImgError(true)}
          />
        ) : (
          <div className="mono-av">{getInitials(partner.name)}</div>
        )}
      </div>
      <span>{partner.name}</span>
    </>
  );

  if (partner.website) {
    return (
      <a
        className="mtile"
        href={partner.website}
        target="_blank"
        rel="noopener noreferrer"
      >
        {tileContent}
      </a>
    );
  }

  return <div className="mtile">{tileContent}</div>;
}

